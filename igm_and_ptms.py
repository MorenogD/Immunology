len(sequences_with_invalid_chars)

gptm_dataframes = {}
for ptm in ptms:
    gptm_dataframes[ptm] = sequences_with_invalid_chars[
        sequences_with_invalid_chars['Epitope - Name'].str.contains(ptm, na=False)
    ]

for ptm, df in gptm_dataframes.items():
    print(f"Data for PTM: {ptm}")
    display(df.head())

for i in gptm_dataframes:
  print(i,len(gptm_dataframes[i]))

import matplotlib.pyplot as plt
import pandas as pd

ptm_counts_igm = {ptm: len(df) for ptm, df in ptm_dataframes.items()}
ptm_counts_igg = {ptm: len(df) for ptm, df in gptm_dataframes.items()}

ptm_counts_df = pd.DataFrame({
    'PTM': list(ptm_counts_igm.keys()),
    'IgM': list(ptm_counts_igm.values()),
    'IgG': list(ptm_counts_igg.values())
})

ptm_counts_df.set_index('PTM').plot(kind='bar', figsize=(12, 6), color=['skyblue', 'salmon'])
plt.title('Frequency of PTMs in IgM and IgG Autoinmune Epitopes')
plt.xlabel('PTM')
plt.ylabel('Frequency')
plt.xticks(rotation=45, ha='right')
plt.legend(title='Antibody Type')
plt.tight_layout()
plt.show()

