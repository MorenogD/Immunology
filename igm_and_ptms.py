df= pd.read_csv('igg-autoinmune.csv')

df= df[['Epitope - Name']]

# Función para encontrar secuencias con '+' o espacios
sequences_with_invalid_chars = df[df['Epitope - Name'].str.contains(r'[+\s]', na=False)]

